/**
 * PulseID Centralized API Client
 *
 * Implements typed, authenticated HTTP communication with the PulseID backend.
 * Base URL: NEXT_PUBLIC_API_BASE_URL (defaults to Cloud Run deployment)
 *
 * Key guarantees:
 * - Injects Authorization: Bearer <token> when authenticated.
 * - Injects lang: en header.
 * - Does not override Content-Type for FormData / multipart requests.
 * - Safely handles empty bodies, non-JSON error payloads, and network timeouts.
 * - Categorizes errors without silently falling back to fake/mock data.
 * - Distinguishes 500 server errors from 401 auth errors (backend bug: unauthenticated requests sometimes 500).
 */

import { BackendEnvelope } from "./types";

/**
 * Resolves the API Base URL.
 * Fails fast and clearly when NEXT_PUBLIC_API_BASE_URL is not set.
 * Silent fallback to production has been removed to prevent accidental data transmission.
 */
export function resolveApiBaseUrl(explicitUrl?: string): string {
  if (explicitUrl && explicitUrl.trim()) {
    return explicitUrl.replace(/\/+$/, "");
  }
  const envUrl = process.env.NEXT_PUBLIC_API_BASE_URL;
  if (!envUrl || !envUrl.trim()) {
    throw new Error(
      "Configuration Error: NEXT_PUBLIC_API_BASE_URL is not set. " +
      "An explicit API base URL is required to prevent accidental data submission to an unintended environment. " +
      "Please set NEXT_PUBLIC_API_BASE_URL in your environment or .env.local file."
    );
  }
  return envUrl.replace(/\/+$/, "");
}

export const AUTH_TOKEN_KEY = "pulseid_auth_token";
export const AUTH_ROLE_KEY = "pulseid_auth_role";
export const AUTH_USER_ID_KEY = "pulseid_auth_user_id";

// Legacy keys for cleanup
const LEGACY_TOKEN_KEYS = ["pulseid_patient_token"];

/**
 * Token Storage Helper
 * Provides consistent browser-side access to the active auth token.
 *
 * Ground Rules:
 * - Legitimate backend tokens are treated as completely opaque (never assumed to be JWTs).
 * - Legacy simulation/demo tokens are rejected by prefix and purged.
 * - Stored token presence does NOT imply a validated session.
 */
export const TokenStorage = {
  get(): string | null {
    if (typeof window === "undefined") return null;
    try {
      const token = localStorage.getItem(AUTH_TOKEN_KEY);
      if (token && !TokenStorage.isFakeToken(token)) {
        return token;
      }
      // Check legacy key if primary is absent
      for (const legacyKey of LEGACY_TOKEN_KEYS) {
        const legacy = localStorage.getItem(legacyKey);
        if (legacy && !TokenStorage.isFakeToken(legacy)) {
          // Migrate
          localStorage.setItem(AUTH_TOKEN_KEY, legacy);
          localStorage.removeItem(legacyKey);
          return legacy;
        }
      }
      return null;
    } catch {
      return null;
    }
  },

  set(token: string | null): void {
    if (typeof window === "undefined") return;
    try {
      if (token && !TokenStorage.isFakeToken(token)) {
        localStorage.setItem(AUTH_TOKEN_KEY, token);
      } else {
        localStorage.removeItem(AUTH_TOKEN_KEY);
      }
      // Clean legacy keys
      for (const legacyKey of LEGACY_TOKEN_KEYS) {
        localStorage.removeItem(legacyKey);
      }
    } catch {
      // Storage unavailable (e.g. private mode quota)
    }
  },

  clear(): void {
    if (typeof window === "undefined") return;
    try {
      localStorage.removeItem(AUTH_TOKEN_KEY);
      localStorage.removeItem(AUTH_ROLE_KEY);
      localStorage.removeItem(AUTH_USER_ID_KEY);
      for (const legacyKey of LEGACY_TOKEN_KEYS) {
        localStorage.removeItem(legacyKey);
      }
    } catch {
      // Storage unavailable
    }
  },

  /**
   * Identifies fake/demo tokens generated by legacy simulations
   * so they are never converted into authenticated sessions.
   *
   * Any other non-empty string is treated as an opaque backend token.
   * Does NOT reject tokens based on structure or enforce JWT formatting.
   */
  isFakeToken(token: string): boolean {
    if (!token || typeof token !== "string" || !token.trim()) return true;
    const trimmed = token.trim();
    return (
      trimmed.startsWith("pulseid_jwt_demo_") ||
      trimmed.startsWith("pulseid_jwt_offline_") ||
      trimmed.startsWith("pulseid_token_local_") ||
      trimmed.startsWith("mock_jwt_token_") ||
      trimmed.startsWith("pulseid_token_") ||
      trimmed === "demo" ||
      trimmed === "offline"
    );
  },
};

/**
 * Categorized API Error Kinds
 */
export type ApiErrorKind =
  | "VALIDATION_ERROR"
  | "BUSINESS_ERROR"
  | "UNAUTHENTICATED"
  | "FORBIDDEN"
  | "NOT_FOUND"
  | "SERVER_ERROR"
  | "NETWORK_ERROR"
  | "TIMEOUT_ERROR";

export class ApiError extends Error {
  readonly kind: ApiErrorKind;
  readonly statusCode?: number;
  readonly validationErrors?: Record<string, string[]>;
  readonly rawBody?: unknown;

  constructor(params: {
    message: string;
    kind: ApiErrorKind;
    statusCode?: number;
    validationErrors?: Record<string, string[]>;
    rawBody?: unknown;
  }) {
    super(params.message);
    this.name = "ApiError";
    this.kind = params.kind;
    this.statusCode = params.statusCode;
    this.validationErrors = params.validationErrors;
    this.rawBody = params.rawBody;
  }

  get isAuthError(): boolean {
    return this.kind === "UNAUTHENTICATED";
  }

  get isValidationError(): boolean {
    return this.kind === "VALIDATION_ERROR";
  }
}

export interface RequestOptions {
  headers?: Record<string, string>;
  signal?: AbortSignal;
  timeoutMs?: number;
  lang?: string;
  skipAuth?: boolean;
}

export interface ApiResponse<T> {
  success: boolean;
  data?: T;
  error?: string;
  statusCode: number;
  validationErrors?: Record<string, string[]>;
}

const DEFAULT_TIMEOUT_MS = 15000;

export class ApiClient {
  private readonly explicitBaseUrl?: string;

  constructor(baseUrl?: string) {
    this.explicitBaseUrl = baseUrl ? baseUrl.replace(/\/+$/, "") : undefined;
  }

  getBaseUrl(): string {
    return resolveApiBaseUrl(this.explicitBaseUrl);
  }

  /**
   * Builds the absolute URL for a request path
   */
  buildUrl(path: string): string {
    const base = this.getBaseUrl();
    const cleanPath = path.startsWith("/") ? path : `/${path}`;
    return `${base}${cleanPath}`;
  }

  /**
   * Core request dispatcher with header injection, timeout, and response normalization.
   */
  async request<T>(
    method: "GET" | "POST" | "PUT" | "DELETE",
    path: string,
    body?: unknown,
    options: RequestOptions = {}
  ): Promise<ApiResponse<T>> {
    const url = this.buildUrl(path);
    const timeoutMs = options.timeoutMs ?? DEFAULT_TIMEOUT_MS;

    // Timeout & Cancellation
    const controller = new AbortController();
    const timeoutId = setTimeout(() => controller.abort(), timeoutMs);

    if (options.signal) {
      options.signal.addEventListener("abort", () => controller.abort());
    }

    // Build Headers
    const headers: Record<string, string> = {
      lang: options.lang || "en",
      ...options.headers,
    };

    // Inject Authorization header if token exists and skipAuth is not true
    if (!options.skipAuth) {
      const token = TokenStorage.get();
      if (token && !headers["Authorization"]) {
        headers["Authorization"] = `Bearer ${token}`;
      }
    }

    // Prepare Body & Content-Type
    let requestBody: BodyInit | undefined = undefined;
    const isFormData = typeof FormData !== "undefined" && body instanceof FormData;

    if (body !== undefined && body !== null) {
      if (isFormData) {
        requestBody = body as FormData;
        // Do NOT set Content-Type: browser sets multipart/form-data with boundary
      } else if (typeof body === "string") {
        requestBody = body;
        if (!headers["Content-Type"]) {
          headers["Content-Type"] = "application/json";
        }
      } else {
        requestBody = JSON.stringify(body);
        if (!headers["Content-Type"]) {
          headers["Content-Type"] = "application/json";
        }
      }
    }

    let response: Response;
    try {
      response = await fetch(url, {
        method,
        headers,
        body: requestBody,
        signal: controller.signal,
      });
    } catch (err: unknown) {
      clearTimeout(timeoutId);

      if (err instanceof DOMException && err.name === "AbortError") {
        throw new ApiError({
          message: `Request timed out after ${timeoutMs}ms`,
          kind: "TIMEOUT_ERROR",
        });
      }

      const errorMessage = err instanceof Error ? err.message : "Network connection failure";
      throw new ApiError({
        message: `Failed to connect to backend (${this.getBaseUrl()}): ${errorMessage}`,
        kind: "NETWORK_ERROR",
        rawBody: err,
      });
    } finally {
      clearTimeout(timeoutId);
    }

    // Read Response Text
    const rawText = await response.text();
    let parsedJson: unknown = null;
    if (rawText && rawText.trim().length > 0) {
      try {
        parsedJson = JSON.parse(rawText);
      } catch {
        // Non-JSON response (e.g. plain text error, HTML from gateway)
        parsedJson = null;
      }
    }

    // Process HTTP Errors (400+)
    if (!response.ok) {
      this.handleHttpError(response.status, parsedJson, rawText);
    }

    // Process Successful Response (200-299)
    return this.normalizeSuccessResponse<T>(response.status, parsedJson);
  }

  /**
   * Normalizes successful HTTP responses
   */
  private normalizeSuccessResponse<T>(status: number, json: unknown): ApiResponse<T> {
    if (json === null || json === undefined) {
      return {
        success: true,
        statusCode: status,
        data: undefined,
      };
    }

    // Check if response is wrapped in standard backend envelope: { code, data, ... }
    const envelope = json as BackendEnvelope<T>;
    if (typeof envelope === "object" && envelope !== null && "data" in envelope && envelope.data !== undefined) {
      return {
        success: true,
        statusCode: status,
        data: envelope.data as T,
      };
    }

    // Direct object or array response
    return {
      success: true,
      statusCode: status,
      data: json as T,
    };
  }

  /**
   * Maps HTTP error responses to typed ApiErrors
   */
  private handleHttpError(status: number, json: unknown, rawText: string): never {
    const errorBody = (typeof json === "object" && json !== null ? json : {}) as Record<string, unknown>;

    // Case 1: ASP.NET Validation Error (400 with "errors" object)
    if (status === 400 && errorBody.errors && typeof errorBody.errors === "object") {
      const validationErrors = errorBody.errors as Record<string, string[]>;
      const firstKey = Object.keys(validationErrors)[0];
      const firstMessage = firstKey && validationErrors[firstKey]?.[0];
      const message =
        firstMessage ||
        (errorBody.title as string) ||
        "One or more validation errors occurred.";

      throw new ApiError({
        message,
        kind: "VALIDATION_ERROR",
        statusCode: status,
        validationErrors,
        rawBody: json,
      });
    }

    // Case 2: Business Error (e.g. 400 with { code: 404, error: "user not found" })
    if (status === 400 && (errorBody.error || errorBody.message)) {
      const message = (errorBody.error as string) || (errorBody.message as string);
      throw new ApiError({
        message,
        kind: "BUSINESS_ERROR",
        statusCode: status,
        rawBody: json,
      });
    }

    // Case 3: 401 Unauthenticated
    if (status === 401) {
      throw new ApiError({
        message: "Authentication required. Please sign in to continue.",
        kind: "UNAUTHENTICATED",
        statusCode: status,
        rawBody: json,
      });
    }

    // Case 4: 403 Forbidden
    if (status === 403) {
      throw new ApiError({
        message: "You do not have permission to access this healthcare resource.",
        kind: "FORBIDDEN",
        statusCode: status,
        rawBody: json,
      });
    }

    // Case 5: 404 Not Found
    if (status === 404) {
      throw new ApiError({
        message: (errorBody.error as string) || "The requested resource was not found.",
        kind: "NOT_FOUND",
        statusCode: status,
        rawBody: json,
      });
    }

    // Case 6: 500 Server Error
    // NOTE: The backend returns 500 for some unauthenticated requests.
    // We treat it as SERVER_ERROR, not UNAUTHENTICATED.
    if (status >= 500) {
      const serverMessage =
        (errorBody.error as string) ||
        (errorBody.message as string) ||
        (rawText && rawText.length < 200 ? rawText : "Internal server error occurred on backend.");

      throw new ApiError({
        message: `Backend server error (${status}): ${serverMessage}`,
        kind: "SERVER_ERROR",
        statusCode: status,
        rawBody: json,
      });
    }

    // Default Fallback
    throw new ApiError({
      message: (errorBody.error as string) || (errorBody.message as string) || `Request failed with status ${status}`,
      kind: "BUSINESS_ERROR",
      statusCode: status,
      rawBody: json,
    });
  }

  // Convenience Methods
  async get<T>(path: string, options?: RequestOptions): Promise<ApiResponse<T>> {
    return this.request<T>("GET", path, undefined, options);
  }

  async post<T>(path: string, body?: unknown, options?: RequestOptions): Promise<ApiResponse<T>> {
    return this.request<T>("POST", path, body, options);
  }

  async put<T>(path: string, body?: unknown, options?: RequestOptions): Promise<ApiResponse<T>> {
    return this.request<T>("PUT", path, body, options);
  }

  async delete<T>(path: string, options?: RequestOptions): Promise<ApiResponse<T>> {
    return this.request<T>("DELETE", path, undefined, options);
  }
}

// Global Singleton Instance
export const apiClient = new ApiClient();
